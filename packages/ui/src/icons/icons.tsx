/**
 * THE ICON SET — one family, one grid, three sizes.
 *
 * Every glyph is Phosphor (MIT), drawn by one hand on one 256 grid. The names
 * below are the product's own and never change, so a call site says what the
 * icon MEANS (IconMatch) and this file decides what it LOOKS like.
 *
 * Sizes: 16 inline with text, 20 in menus/buttons/rows, 24 in headers and
 * tiles. Nothing else (the icons guardrail test pins it for new code).
 *
 * Weights: "regular" at rest, "fill" for the selected item (the active nav
 * entry, a set toggle, a filled star), "duotone" for feature tiles and empty
 * states, "bold" only where a glyph sits on a coloured fill under 16px.
 *
 * Every icon inherits `currentColor`, so it reads correctly in Daylight and
 * Floodlight. Decorative by default (aria-hidden): the parent carries the
 * accessible name. Pass `aria-hidden={false}` with `alt` for an icon that
 * stands alone.
 */
export type IconWeight = "regular" | "fill" | "duotone" | "bold";

export interface IconProps extends Omit<SVGProps<SVGSVGElement>, "ref" | "color"> {
  /** Rendered width and height in px: 16, 20 (default) or 24. */
  size?: number;
  weight?: IconWeight;
  /** Accessible title, for the rare icon that stands alone. */
  alt?: string;
}

type Glyph = typeof ArrowLeftIcon;

function draw(
  Glyph: Glyph,
  { size = 20, weight = "regular", ...props }: IconProps,
  fixed?: IconWeight,
) {
  return <Glyph size={size} weight={fixed ?? weight} aria-hidden {...props} />;
}

